"""
synthetic_data.py
Generate a SYNTHETIC dataset in exactly the file formats the real-data tools expect
(visibility CSV, METAR text, measurement log, truth), so the whole pipeline can be exercised end-to-end
before real partner data arrive.

!!! This is NOT real data and proves nothing about reality. It is generated by this project's own sensor
!!! model. Its only legitimate uses: (1) test the parsers, QC, replay and calibration code, (2) show a data
!!! provider the expected format. Every file is stamped SYNTHETIC in its header.
"""
from __future__ import annotations

import argparse
import os
from typing import Optional

import numpy as np
import pandas as pd

from .fog import FogScenario
from .fogdata import FogCalibration, FogProfile
from .radar import RadarSensor
from .sensor import FalconEyeSensor

STAMP = "# SYNTHETIC DATA generated by falcon_eye.synthetic_data - NOT real measurements\n"

METAR_SAMPLE = """# SYNTHETIC METARs (fake station XXXX) - format examples only
2024/01/05 00:00 METAR XXXX 050000Z 18004KT 9999 FEW030 08/06 Q1019
2024/01/05 01:00 METAR XXXX 050100Z 18003KT 6000 BR SCT005 07/06 Q1019
2024/01/05 02:00 METAR XXXX 050200Z VRB02KT 2500 BR BKN003 06/06 Q1020
2024/01/05 03:00 METAR XXXX 050300Z 00000KT 0800 FG VV002 05/05 Q1020
2024/01/05 04:00 METAR XXXX 050400Z 00000KT 0350 FG VV001 05/05 Q1020 R28L/0400V0600U
2024/01/05 05:00 METAR XXXX 050500Z 02003KT 1500 BR OVC002 06/06 Q1021
2024/01/05 06:00 METAR XXXX 050600Z 02005KT CAVOK 09/06 Q1022
2024/01/05 07:00 METAR KXXX 050700Z 18005KT 1 1/2SM BR OVC004 04/03 A2992
2024/01/05 08:00 METAR KXXX 050800Z 18006KT P6SM FEW050 08/04 A2993
"""


def generate_dataset(outdir, n_episodes=12, seed=0, world: Optional[FogCalibration] = None,
                     duration_s=100.0, dt=0.1, include_sigma=True, dirty=False, lidar_wavelength_nm=None,
                     vis_range_m=(80.0, 20000.0)) -> dict:
    """`world` is the 'true' fog calibration used to generate the data (default: qualitative anchors).
    Pass a different one (or extinction_scale) to test that calibration recovers it."""
    os.makedirs(outdir, exist_ok=True)
    rng = np.random.default_rng(seed)
    world = world or FogCalibration()
    lidar = FalconEyeSensor(rng=np.random.default_rng(rng.integers(1 << 31)), wavelength_nm=lidar_wavelength_nm)
    radar = RadarSensor(rng=np.random.default_rng(rng.integers(1 << 31)))
    mrows, trows, vrows = [], [], []
    t0 = 0.0
    for ep in range(n_episodes):
        v0 = 10 ** rng.uniform(np.log10(vis_range_m[0]), np.log10(vis_range_m[1]))
        drift = rng.uniform(-0.25, 0.25)                      # decades over the episode
        prof = FogProfile.from_schedule([(0.0, v0), (duration_s, float(np.clip(v0 * 10 ** drift, 50, 30000)))], world)
        r0 = rng.uniform(3000, 8500); vc = rng.uniform(40, 150); lat = rng.uniform(-300, 300); appear = 8.0
        n = int(duration_s / dt)
        for k in range(n):
            t = k * dt; tg = t0 + t
            present = t >= appear
            r = r0 - vc * (t - appear) if present else np.nan
            if present and r < 150:
                break
            ang = float(np.arctan2(lat, r)) if present else 0.0
            fog = prof.at(t)
            if k % 10 == 0:
                vrows.append((round(tg, 3), round(prof.visibility_at(t), 1)))
            trows.append(dict(time_s=round(tg, 3), episode=ep, true_range_m=r if present else np.nan,
                              true_closing_mps=vc if present else np.nan, true_angle_rad=ang if present else np.nan,
                              target_present=int(present)))
            tr_r = r if present else 1e9
            sens = [("lidar", lidar.measure(tr_r, ang, vc, fog))]
            if k % 2 == 0:
                sens.append(("radar", radar.measure(tr_r, ang, vc, fog)))
            for name, m in sens:
                row = dict(time_s=round(tg, 3), episode=ep, sensor=name, detected=int(m.target_detected))
                if m.target_detected:
                    row.update(range_m=m.estimated_range, angle_rad=m.relative_angle, closing_speed_mps=m.relative_velocity,
                               confidence=m.confidence)
                    if include_sigma:
                        row.update(range_sigma_m=m.range_sigma_m, angle_sigma_rad=m.angle_sigma_rad,
                                   velocity_sigma_mps=m.velocity_sigma_mps)
                mrows.append(row)
        t0 += duration_s + 20.0
    meas = pd.DataFrame(mrows); truth = pd.DataFrame(trows); vis = pd.DataFrame(vrows, columns=["time_s", "visibility_m"])
    if dirty:                                   # corrupt the files the way real logs get corrupted
        d = rng.choice(meas.index[meas["detected"] == 1], size=max(5, len(meas) // 40), replace=False)
        meas.loc[d[: len(d) // 2], "range_m"] = np.nan
        meas.loc[d[len(d) // 2:], "range_m"] = -5.0
        meas = pd.concat([meas, meas.sample(20, random_state=1)])
        sw = rng.choice(len(meas), 40, replace=False); meas.iloc[sw] = meas.iloc[sw[::-1]].to_numpy()
        meas["sensor"] = meas["sensor"].map(lambda s: s.upper() + " " if rng.random() < 0.1 else s)
        vis.loc[vis.sample(5, random_state=2).index, "visibility_m"] = -9999
    paths = dict(measurements=os.path.join(outdir, "measurements.csv"), truth=os.path.join(outdir, "truth.csv"),
                 visibility=os.path.join(outdir, "visibility_m.csv"), metar=os.path.join(outdir, "metar_sample.txt"))
    for key, df in (("measurements", meas), ("truth", truth), ("visibility", vis)):
        with open(paths[key], "w", newline="") as f:
            f.write(STAMP); df.to_csv(f, index=False)
    open(paths["metar"], "w").write(METAR_SAMPLE)
    return paths


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate a SYNTHETIC example dataset (format demonstration / pipeline test).")
    ap.add_argument("--out", default="synthetic_dataset"); ap.add_argument("--episodes", type=int, default=12)
    ap.add_argument("--seed", type=int, default=0); ap.add_argument("--dirty", action="store_true")
    a = ap.parse_args(argv)
    print(generate_dataset(a.out, a.episodes, a.seed, dirty=a.dirty))


if __name__ == "__main__":
    main()
